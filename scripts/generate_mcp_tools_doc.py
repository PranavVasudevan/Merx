"""Regenerate docs/api/mcp-tools.md from the real `banklens_mcp.tools.TOOLS`
registry and `banklens_mcp.authz.MCP_TOOL_TIERS` — see that file's own header
for why this exists (hand-editing it drifts from the registry silently; this
script is the "regenerate it" instruction at its own bottom, made real rather
than left as pseudocode).

    python scripts/generate_mcp_tools_doc.py            # writes docs/api/mcp-tools.md
    python scripts/generate_mcp_tools_doc.py --check     # exits 1 if the committed
                                                           # file would change (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT_PATH = REPO / "docs" / "api" / "mcp-tools.md"

for rel in ("services/mcp-server/src", "pipelines/transforms/src"):
    p = REPO / rel
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

_HEADER_TEMPLATE = """# MCP tool registry

The MCP server (`services/mcp-server`) exposes {count} tools — every one is a thin
wrapper: read Gold/feature functions, return a JSON-serialisable result. The
exact same functions power the ingestion/transforms CLIs and the REST bridge
(`services/api-gateway`), so there is one implementation of every feature, not
three. This document is generated by walking the real
`banklens_mcp.tools.TOOLS` registry and `banklens_mcp.authz.MCP_TOOL_TIERS`
directly — regenerate it (see the bottom of this file) rather than hand-editing
if the registry changes.

## Authorization tier

Every tool is tagged **viewer** (any authenticated `viewer` or `analyst` role)
or **analyst** (analyst role required — the heavier what-if simulators: stress
tests, bulk/comparison/surface variants, correlated scenarios). This is
enforced per-call inside the MCP server itself
(`services/mcp-server/src/banklens_mcp/authz.py`) against the same OPA policy
(`platform/auth/opa/policy.rego`) the REST bridge evaluates its routes
against — see `platform/auth/README.md`. `services/mcp-server/tests/test_authz.py`
fails CI if this file's tiers ever drift from the Rego source of truth.

A tool listed below as **UNTIERED** is missing from `MCP_TOOL_TIERS` entirely
right now — a real, currently-open gap (the same one `test_authz.py`'s
`test_every_tool_is_tiered` fails on), not a rendering artifact of this
generator. It means that tool has no per-call authorization enforced for it
until `MCP_TOOL_TIERS` is fixed.

## Params notation

`**name**: type` — required. `name: type` — optional. `enum(a|b|c)` — a
fixed set of allowed string values.

## Tools
"""

_FOOTER = """
## Regenerating this document

```
python scripts/generate_mcp_tools_doc.py
```
"""


def _param_str(name: str, schema: dict, required: set[str]) -> str:
    if "enum" in schema:
        type_str = f"enum({'|'.join(schema['enum'])})"
    else:
        type_str = schema.get("type", "any")
    label = f"**{name}**: {type_str}" if name in required else f"{name}: {type_str}"
    return label


def render() -> str:
    from banklens_mcp.authz import MCP_TOOL_TIERS
    from banklens_mcp.tools import TOOLS

    parts = [_HEADER_TEMPLATE.format(count=len(TOOLS))]
    for tool in TOOLS:
        name = tool["name"]
        tier = MCP_TOOL_TIERS.get(name) or "UNTIERED"
        schema = tool.get("inputSchema") or {}
        properties: dict = schema.get("properties") or {}
        required = set(schema.get("required") or [])
        if properties:
            params = ", ".join(_param_str(p, s, required) for p, s in properties.items())
        else:
            params = "(none)"
        parts.append(f"\n### `{name}` — {tier}\n\n{tool['description']}\n\nParams: {params}\n")
    parts.append(_FOOTER)
    return "".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if docs/api/mcp-tools.md is stale, without writing it")
    args = ap.parse_args()

    rendered = render()

    if args.check:
        current = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.exists() else None
        if current == rendered:
            print(f"OK: {OUT_PATH.relative_to(REPO)} is in sync with the MCP tool registry.")
            return 0
        print(f"STALE: {OUT_PATH.relative_to(REPO)} does not match what "
              "banklens_mcp.tools.TOOLS/banklens_mcp.authz.MCP_TOOL_TIERS currently "
              "generate. Run `python scripts/generate_mcp_tools_doc.py` and commit the result.")
        return 1

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUT_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
